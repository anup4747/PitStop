create or replace view public.storefront_products
with (security_invoker = true)
as
select
  coalesce(p.external_id, p.slug) as id,
  p.name,
  c.name as category,
  p.price,
  p.original_price as "originalPrice",
  p.badge,
  p.sku,
  coalesce(i.stock_count, 0) > 0 as "inStock",
  coalesce(i.stock_count, 0) as "stockCount",
  p.short_description as "shortDesc",
  p.full_description as "fullDesc",
  p.specifications as specs,
  p.features,
  p.compatible_with as compatible,
  p.options,
  coalesce(image_list.images, array[]::text[]) as images
from public.products p
join public.categories c on c.id = p.category_id
left join public.inventory i on i.product_id = p.id
left join lateral (
  select array_agg(pi.image_url order by pi.sort_order, pi.id) as images
  from public.product_images pi
  where pi.product_id = p.id
) image_list on true
where p.is_active = true and c.is_active = true;

